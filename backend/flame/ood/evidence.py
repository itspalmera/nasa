"""Read-only experimental evidence and leakage-safe fold previews. No fitting."""
from .data import cohort_rows, eligible, load_dataset, split_gravity
from .schema import OUTPUTS


def inspect_evidence(path, query):
    rows, digest = load_dataset(path)
    rows = cohort_rows(rows, query.fuel, query.configuration, query.temperature_available,
                       exploratory=query.data_mode == 'exploratory')
    outputs = {}
    for output, unit in OUTPUTS.items():
        measured = [r for r in rows if r.outputs.get(output) is not None]
        if not measured:
            continue
        points = [{
            'id': r.experiment_id, 'gravity_g': r.gravity_g, 'oxygen_pct': r.oxygen_pct,
            'pressure_kpa': r.pressure_kpa, 'airflow_cm_s': r.airflow_cm_s,
            'temperature_k': r.temperature_k, 'observed': r.outputs[output],
            'measurement_sd': r.uncertainty.get(output), 'reviewed': r.reviewed,
            'source': r.source, 'citation': r.citation, 'leakage_group': r.leakage_group,
            'provenance': r.provenance,
        } for r in measured]
        preview = None
        if query.gravity_g is not None:
            train, test, groups = split_gravity(measured, query.gravity_g)
            before = [r for r in measured if r.gravity_g != query.gravity_g]
            levels = sorted({r.gravity_g for r in train})
            reasons = []
            if not test:
                reasons.append('No observations for this output at the selected gravity.')
            if query.data_mode == 'exploratory':
                reasons.append('Exploratory mode permits evidence inspection but not reviewed scientific validation.')
            removed = len(before) - len(train)
            if removed:
                reasons.append(f'{removed} observations at other gravities share dependency groups with the held-out rows and must also be excluded.')
            if len(train) < 3:
                reasons.append(f'Only {len(train)} training rows without held-out group overlap remain; at least 3 are required by the fitting protocol.')
            if len(levels) < 2:
                reasons.append(f'Only {len(levels)} training gravity levels without held-out group overlap remain; this LOGO protocol requires at least 2.')
            preview = {
                'gravity_g': query.gravity_g, 'held_out_n': len(test),
                'remaining_before_group_exclusion': len(before), 'related_rows_removed': removed,
                'remaining_training_n': len(train), 'remaining_gravity_levels': levels,
                'excluded_groups': sorted(groups), 'data_split_eligible': bool(test) and eligible(train),
                'validation_allowed': query.data_mode == 'reviewed' and bool(test) and eligible(train),
                'reasons': reasons,
            }
        outputs[output] = {
            'unit': unit, 'observations': points, 'fold_preview': preview,
            'by_gravity': [{'gravity_g': g, 'observations': sum(r.gravity_g == g for r in measured),
                            'reviewed': sum(r.gravity_g == g and r.reviewed for r in measured)}
                           for g in sorted({r.gravity_g for r in measured})],
        }
    return {
        'status': 'available' if outputs else 'unavailable',
        'reason': None if outputs else 'No compatible observed outputs in this cohort and data mode.',
        'dataset_sha256': digest, 'request': query.model_dump(),
        'evidence_version': 'ood-evidence-v1', 'model_fitted': False,
        'cohort_observations': len(rows), 'dependency_groups': len({r.leakage_group for r in rows}),
        'outputs': outputs,
        'gravity_note': '0 g denotes nominal microgravity in the imported NASA tables, not a measured zero residual acceleration.'
                        if any(r.gravity_g == 0 and r.provenance == 'microgravity' for r in rows) else None,
        'limitations': [
            'Rows are source-linked transcriptions; their reviewed flag is preserved.',
            'Recorded conditions vary between observations. A plot is not a controlled causal comparison.',
            'Measurements are not model predictions. No validation metrics or confidence intervals are generated by inspection.',
            'Missing measurement standard deviations remain unavailable; they are not treated as zero.',
        ],
    }
